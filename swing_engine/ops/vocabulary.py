"""Generate docs/vocabulary.md: every registered strategy with its one-line definition, status and dated operator
rulings (docs/proposals/video-model-plan.md, P0 item 4).

Definitions come from the strategy cards (docs/strategies/<slug>.md: front matter + "One-line summary"); rulings are
hand-written in docs/rulings.md as ``- YYYY-MM-DD <slug>: text`` lines (slug ``*`` applies to everything). Run::

    uv run python -m swing_engine.ops.vocabulary
"""
from __future__ import annotations

import re
from collections import defaultdict
from pathlib import Path

from swing_engine.core import registry

ROOT = Path(__file__).resolve().parents[2]
CARDS = ROOT / "docs" / "strategies"
RULINGS = ROOT / "docs" / "rulings.md"
OUT = ROOT / "docs" / "vocabulary.md"
STRUCTURE_DOC = "market-structure.md"
_RULING = re.compile(r"^-\s*(\d{4}-\d{2}-\d{2})\s+([\w*@.-]+):\s*(.+)$")
_FRONT = re.compile(r"^(\w+):\s*(.*?)\s*(?:#.*)?$")
STRUCTURE_SECTIONS = ("Swings", "Structure", "Liquidity", "Imbalance", "Zones (order blocks)", "Other")
_KIND_HEAD = re.compile(r"^(?:-\s+)?((?:\*\*`[^*]+\*\*(?:\s+and\s+)?)+)[.:,]?\s*(.*)$", re.S)


def read_card(path: Path) -> dict[str, str]:
    """Front-matter scalars plus ``summary`` (the paragraph under "## One-line summary"); empty when no card."""
    if not path.exists():
        return {}
    text = path.read_text()
    out: dict[str, str] = {}
    if text.startswith("---"):
        for line in text.split("---", 2)[1].splitlines():
            m = _FRONT.match(line)
            if m:
                out[m.group(1)] = m.group(2)
    m = re.search(r"^## One-line summary\s*\n(.+?)(?:\n\s*\n|\n#|\Z)", text, re.S | re.M)
    if m:
        out["summary"] = " ".join(m.group(1).split())
    return out


def read_rulings(path: Path = RULINGS) -> dict[str, list[tuple[str, str]]]:
    out: dict[str, list[tuple[str, str]]] = defaultdict(list)
    for line in path.read_text().splitlines() if path.exists() else []:
        m = _RULING.match(line.strip())
        if m:
            out[m.group(2)].append((m.group(1), m.group(3)))
    return out


def entries() -> list[dict[str, object]]:
    rulings = read_rulings()
    rows = []
    for slug in registry.names("strategy"):
        card = read_card(CARDS / f"{slug}.md")
        rows.append({"slug": slug, "name": card.get("name", slug), "status": card.get("status", ""),
                     "grade": card.get("evidence_grade", ""), "summary": card.get("summary", ""),
                     "has_card": bool(card), "rulings": sorted(rulings.get(slug, []))})
    return rows


def structure_entries(path: Path | None = None) -> list[dict[str, object]]:
    """Market-structure event kinds with their written definition, read from docs/market-structure.md: under each
    kind section, a paragraph or list item that opens with a bold back-ticked kind starts an entry, and the plain
    list items right after it belong to it."""
    path = path or ROOT / "docs" / STRUCTURE_DOC
    rows: list[dict[str, object]] = []
    section, current, blocks = "", None, []
    for line in [*(path.read_text().splitlines() if path.exists() else []), ""]:
        if line.strip() and not line.startswith(("#", "- ")) and blocks and blocks[-1] is not None:
            blocks[-1][1] += " " + line.strip()  # continuation of the paragraph / list item above
        elif line.startswith("## "):
            section = line[3:].strip()
            blocks.append(None)
        elif line.strip() and not line.startswith("#"):
            blocks.append([section, line.strip()])
        else:
            blocks.append(None)
    for block in blocks:
        if block is None or block[0] not in STRUCTURE_SECTIONS:
            current = None if block is not None else current
            continue
        m = _KIND_HEAD.match(block[1])
        if m:
            current = {"section": block[0], "kinds": re.findall(r"`(\w+)`", m.group(1)), "definition": m.group(2)}
            rows.append(current)
        elif block[1].startswith("- ") and current is not None:
            current["definition"] = f"{current['definition']}\n{block[1]}"
        else:
            current = None
    return rows


def render() -> str:
    rulings = read_rulings()
    lines = ["# Tracked vocabulary", "",
             "Generated by `swing_engine.ops.vocabulary`; do not edit by hand. Every strategy the engine tracks, its "
             "definition from its card, and dated operator rulings from `docs/rulings.md`. Intraday market-structure "
             f"event kinds are defined in [{STRUCTURE_DOC}]({STRUCTURE_DOC}).", ""]
    if rulings.get("*"):
        lines += ["## Rulings that apply to everything", ""]
        lines += [f"- {d}: {t}" for d, t in sorted(rulings["*"])] + [""]
    lines += ["## Strategies", ""]
    for e in entries():
        tags = ", ".join(x for x in (e["status"], f"evidence {e['grade']}" if e["grade"] else "") if x)
        link = f"[{e['slug']}](strategies/{e['slug']}.md)" if e["has_card"] else f"{e['slug']} (no card)"
        lines.append(f"### {link}" + (f" ({tags})" if tags else ""))
        lines.append(str(e["summary"] or e["name"]))
        lines += [f"- operator ruling {d}: {t}" for d, t in e["rulings"]]
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.write_text(render())
    print(f"{len(entries())} strategies -> {OUT.relative_to(ROOT)}")
