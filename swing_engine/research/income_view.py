"""Steady income, or not: the portfolios already replayed, read the way the owner defined winning (2026-10-13:
"consistent revenue streams that I can scale").

Descriptive only: no rule, no pass or fail, no new trial. Every row is a single-strategy replay that was run for
a pre-registered test (``runs/replay/*_prereg*.json``), net of the replay's costs, on $100k. For each: yearly return,
share of months that made money, the worst month, the deepest drop, how much of the money was invested, and the same
for buy-and-hold SPY over the same sessions (price only, from the store's bars).

    uv run python -m swing_engine.research.income_view --settings config/replay_events.yaml
"""
from __future__ import annotations

import argparse
import json
import math
from collections.abc import Sequence
from pathlib import Path

import pandas as pd

from swing_engine.research.cards import MARKET_SYMBOL, ROOT, RUNS_SUBDIR

OUT = "docs/income_view.md"
GLOB = "*_prereg*.json"
MONTHS_PER_YEAR = 12


def monthly_stats(equity: pd.Series) -> dict[str, float]:
    """``equity``: one value per session, date index. Returns per-year return, month hit rate, worst month, max
    drawdown and the longest run of losing months."""
    equity = equity.dropna()
    if len(equity) < 2:
        return dict.fromkeys(("cagr", "months", "pos_months", "worst_month", "max_dd", "losing_run"), math.nan)
    month_end = equity.groupby([equity.index.year, equity.index.month]).last()
    rets = month_end.pct_change()
    rets.iloc[0] = month_end.iloc[0] / equity.iloc[0] - 1.0
    years = (equity.index[-1] - equity.index[0]).days / 365.25
    run = longest = 0
    for r in rets:
        run = run + 1 if r < 0 else 0
        longest = max(longest, run)
    return {"cagr": (equity.iloc[-1] / equity.iloc[0]) ** (1.0 / years) - 1.0 if years > 0 else math.nan,
            "months": float(len(rets)), "pos_months": float((rets > 0).mean()), "worst_month": float(rets.min()),
            "max_dd": float((1.0 - equity / equity.cummax()).max()), "losing_run": float(longest)}


def load_runs(runs_dir: Path) -> list[dict]:
    out = []
    for path in sorted(runs_dir.glob(GLOB)):
        j = json.loads(path.read_text())
        curve = pd.DataFrame(j.get("equity_curve") or [])
        if curve.empty:
            continue
        idx = pd.DatetimeIndex(pd.to_datetime(curve["ts"], utc=True)).tz_convert("America/New_York").tz_localize(None).normalize()
        out.append({"strategy": ",".join(j.get("strategies") or [(j.get("summary") or {}).get("strategy", "?")]),
                    "start": str(j["start"])[:10], "end": str(j["end"])[:10],
                    "equity": pd.Series(curve["equity"].to_numpy(float), index=idx),
                    "exposure": float(pd.to_numeric(curve["exposure"], errors="coerce").mean()),
                    "trades": int((j.get("summary") or {}).get("trades") or 0)})
    return out


def render(runs: Sequence[dict], spy: pd.Series) -> str:
    pct = lambda x, spec=".1%": "-" if x is None or not math.isfinite(x) else format(x, spec)  # noqa: E731
    lines = [
        "# Income view: the portfolios already tested, by steadiness", "",
        "Generated by `swing_engine.research.income_view`. Descriptive: nothing here passes or fails, and no rule was "
        "set in advance. Each row is a one-strategy replay run for a pre-registered test, net of replay costs. Every "
        "one of these FAILED its registered test against SPY (the repurchasers passed an absolute rule and showed no "
        "alpha); see docs/preregistration/. Read this as: what did each make, how often, and how deep were the drops, "
        f"with buy-and-hold {MARKET_SYMBOL} (price only) on the same days for scale. A long-only book makes money "
        "in a rising market whether or not its rule adds anything; both windows here were rising markets.", "",
    ]
    for (start, end), group in pd.DataFrame(runs).groupby(["start", "end"], sort=False):
        bench = monthly_stats(spy.loc[start:end])
        lines += [f"## {start} .. {end}", "",
                  "| portfolio | return / yr | months up | worst month | deepest drop | longest losing run | invested | trades |",
                  "|---|---|---|---|---|---|---|---|"]
        rows = [(r["strategy"], monthly_stats(r["equity"]), r["exposure"], r["trades"]) for r in group.to_dict("records")]
        for name, st, exposure, trades in sorted(rows, key=lambda x: -x[1]["pos_months"]):
            lines.append(f"| {name} | {pct(st['cagr'])} | {pct(st['pos_months'], '.0%')} | {pct(st['worst_month'])} | "
                         f"{pct(st['max_dd'])} | {st['losing_run']:.0f} months | {pct(exposure, '.0%')} | {trades} |")
        lines += [f"| **buy and hold {MARKET_SYMBOL}** | {pct(bench['cagr'])} | {pct(bench['pos_months'], '.0%')} | "
                  f"{pct(bench['worst_month'])} | {pct(bench['max_dd'])} | {bench['losing_run']:.0f} months | 100% | 1 |", ""]
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> None:
    from swing_engine.core.config import load_settings
    from swing_engine.data.store import Store

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--settings", default="config/replay_events.yaml", help="a settings file whose store has SPY bars")
    ap.add_argument("--out", default=OUT)
    args = ap.parse_args(argv)
    store_path = ROOT / load_settings.__wrapped__(Path(args.settings)).data.store_path
    with Store(str(store_path), read_only=True) as store:
        bars = store.read_bars([MARKET_SYMBOL])
    spy = pd.Series(bars["close"].to_numpy(float),
                    index=pd.DatetimeIndex(pd.to_datetime(bars["ts"])).tz_localize(None).normalize())
    runs = load_runs(store_path.parent.joinpath(*RUNS_SUBDIR))
    (ROOT / args.out).write_text(render(runs, spy))
    print(f"{len(runs)} replays -> {args.out}")


if __name__ == "__main__":
    main()
