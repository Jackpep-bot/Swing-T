"""Where, if anywhere, is there an edge? Every replayed strategy split by the liquidity of the stock it signalled.

An exploratory map over the replay shadow ledgers (owner, 2026-10-13: "double down on testing"), not a
pre-registered test: it says where to look next, and what it finds can only be confirmed forward. Each
(strategy, liquidity bucket) is graded like a leaderboard row against SPY (``research.leaderboard``), under the name
``<strategy>@<bucket>``, and every look is logged as a trial.

A cell is a **candidate** when, at the same horizon, it has at least ``MIN_SIGNALS`` traded signals, a positive
net R against SPY and a block t of at least ``T_WEAK`` in BOTH windows. With no edge anywhere a share of cells
passes by luck: about ``P(t >= T_WEAK)^2`` of them, so the report prints that count beside the one found.

    uv run python -m swing_engine.research.edge_map --settings <lane0.yaml> --store <lane1.duckdb>
"""
from __future__ import annotations

import argparse
import math
from collections.abc import Sequence
from datetime import date
from pathlib import Path

import pandas as pd
from scipy.stats import norm

from swing_engine.research.cards import ROOT, WINDOWS, Window, read_shadow, with_costs
from swing_engine.research.leaderboard import leaderboard, log_board_trials
from swing_engine.research.trials import trial_count

OUT = "docs/edge_map.md"
#: 20-day mean dollar volume on the signal day (research.costs), lower bound inclusive
BUCKETS: tuple[tuple[float, float, str], ...] = (
    (0.0, 5e6, "dv<5M"), (5e6, 20e6, "dv5-20M"), (20e6, 100e6, "dv20-100M"), (100e6, math.inf, "dv>100M"))
MIN_SIGNALS = 100  # traded signals per window for a cell to count
T_WEAK, T_STRONG = 1.0, 2.0  # block t in both windows: candidate / strong candidate
SEP = "@"


def bucketed(shadow: pd.DataFrame, tag: str = "") -> pd.DataFrame:
    """``shadow`` with ``strategy`` renamed ``<strategy>@<bucket><tag>`` (rows without a dollar volume are left
    out). ``tag`` names another universe, so its cells are trials of their own."""
    dv = shadow["dollar_volume"].astype(float)
    label = pd.Series(pd.NA, index=shadow.index, dtype=object)
    for lo, hi, name in BUCKETS:
        label[(dv >= lo) & (dv < hi)] = name + tag
    keep = label.notna()
    out = shadow.loc[keep].copy()
    out["strategy"] = out["strategy"].astype(str) + SEP + label[keep].astype(str)
    return out


def candidates(board: pd.DataFrame, t_min: float = T_WEAK, min_signals: int = MIN_SIGNALS) -> tuple[pd.DataFrame, int]:
    """(cells passing in every window at one horizon, one row per cell and window; cells with enough signals in
    every window, i.e. the number that had the chance to pass)."""
    n_windows = board["window"].nunique()
    enough = board.loc[board["n"] >= min_signals]
    full = enough.groupby(["strategy", "horizon"]).size()
    eligible = full[full == n_windows].index
    ok = enough.loc[(enough["rel_r"] > 0) & (enough["t"] >= t_min)]
    counts = ok.groupby(["strategy", "horizon"]).size()
    keep = counts[counts == n_windows].index
    rows = board.set_index(["strategy", "horizon"]).loc[keep].reset_index() if len(keep) else board.iloc[0:0]
    return rows, len(eligible)


def chance(n_cells: int, t_min: float, n_windows: int = 2) -> float:
    """Cells expected to pass by luck when no cell has an edge (independent windows, mean zero)."""
    return n_cells * float(norm.sf(t_min)) ** n_windows


def render(board: pd.DataFrame, pooled: pd.DataFrame, n_trials: int, note: str = "") -> str:
    f = lambda x, spec="+.3f": "-" if x is None or not math.isfinite(x) else format(x, spec)  # noqa: E731
    years = sorted((int(y) for y in board["window"].unique()), reverse=True)
    lines = [
        "# Edge map: every strategy by the liquidity of the stock it signalled", "",
        "Generated by `swing_engine.research.edge_map` from the replay shadow ledgers. Exploratory: it shows where to "
        "look, and anything it finds has been picked from thousands of cells, so only a forward test can confirm it. "
        "Each cell is one strategy's signals on stocks in one band of 20-day average dollar volume, graded like the "
        "leaderboard: net R per signal after costs, minus what SPY returned over the same days (`vs SPY`), t on "
        f"non-overlapping blocks. {n_trials} trials are logged in all, these cells included.", "",
        *([note, ""] if note else []),
        "Costs are half the spread estimated from daily bars, at least 20 bp a side below $50M a day. Real spreads in "
        "the thinnest band are often wider, so its numbers flatter it.", "",
        "## All strategies pooled, by band", "",
        "| band | window | signals | net R | vs SPY |", "|---|---|---|---|---|",
    ]
    for r in pooled.itertuples():
        lines.append(f"| {r.band} | {r.window} | {int(r.n)} | {f(r.net_r)} | {f(r.rel_r)} |")
    for label, t_min in (("Strong candidates", T_STRONG), ("Candidates", T_WEAK)):
        rows, eligible = candidates(board, t_min)
        found = rows.groupby(["strategy", "horizon"]).ngroups if len(rows) else 0
        lines += ["", f"## {label}: positive against SPY with t >= {t_min:g} in both windows", "",
                  f"{found} of {eligible} cells with at least {MIN_SIGNALS} signals in both windows. By luck alone about "
                  f"{chance(eligible, t_min):.1f} would pass."]
        if not found:
            continue
        lines += ["", "| strategy | band | horizon | " + " | ".join(
            f"{y} signals | {y} net R | {y} vs SPY | {y} t" for y in years) + " |", "|" + "---|" * (3 + 4 * len(years))]
        wide = rows.pivot_table(index=["strategy", "horizon"], columns="window", values=["n", "net_r", "rel_r", "t"])
        order = wide["t"].min(axis=1).sort_values(ascending=False).index
        for strat, h in order:
            name, band = strat.split(SEP, 1)
            cells = " | ".join(f"{int(wide.at[(strat, h), ('n', y)])} | {f(wide.at[(strat, h), ('net_r', y)])} | "
                               f"{f(wide.at[(strat, h), ('rel_r', y)])} | {f(wide.at[(strat, h), ('t', y)], '.2f')}"
                               for y in years)
            lines.append(f"| {name} | {band} | {h}d | {cells} |")
    return "\n".join(lines) + "\n"


def pooled_by_band(shadow: pd.DataFrame, windows: Sequence[Window] = WINDOWS) -> pd.DataFrame:
    """Every strategy's signals together, per band and window, at the longest horizon."""
    one = shadow.assign(strategy=shadow["strategy"].astype(str).str.split(SEP).str[1])
    board, _ = leaderboard(one, windows, horizons=(20,), relative=True)
    order = lambda band: next(i for i, (_, _, name) in enumerate(BUCKETS) if str(band).startswith(name))  # noqa: E731
    out = board.rename(columns={"strategy": "band"}).assign(_o=lambda b: b["band"].map(order))
    return out.sort_values(["_o", "window"]).drop(columns="_o")


def main(argv: Sequence[str] | None = None) -> pd.DataFrame:
    from swing_engine.core.config import load_settings

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--settings", default="config/replay.yaml")
    ap.add_argument("--store", action="append", default=[], help="extra replay store (repeatable)")
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--windows", default=None,
                    help="START:END,START:END (ISO dates) instead of the two research windows; each must start in its own year")
    ap.add_argument("--tag", default="", help="added to every band name, so a run on another universe logs its own trials")
    ap.add_argument("--note", default="", help="one paragraph for the top of the report (universe, windows)")
    args = ap.parse_args(argv)
    windows: Sequence[Window] = WINDOWS
    if args.windows:
        windows = [Window(date.fromisoformat(a), date.fromisoformat(b), "") for a, b in
                   (w.split(":") for w in args.windows.split(","))]
    base = ROOT / load_settings.__wrapped__(Path(args.settings)).data.store_path
    shadow = bucketed(with_costs(read_shadow([base, *(ROOT / s for s in args.store)]), base), args.tag)
    board, _ = leaderboard(shadow, windows, relative=True)
    logged = log_board_trials(board)
    board, n_trials = leaderboard(shadow, windows, logged_trials=trial_count(None), relative=True)
    (ROOT / args.out).write_text(render(board, pooled_by_band(shadow, windows), n_trials, args.note))
    strong, weak = candidates(board, T_STRONG)[0], candidates(board, T_WEAK)[0]
    print(f"{len(board)} rows, {logged} new trials, {n_trials} in all; candidates: "
          f"{weak.groupby(['strategy', 'horizon']).ngroups if len(weak) else 0} at t>={T_WEAK:g}, "
          f"{strong.groupby(['strategy', 'horizon']).ngroups if len(strong) else 0} at t>={T_STRONG:g} -> {args.out}")
    return board


if __name__ == "__main__":
    main()
